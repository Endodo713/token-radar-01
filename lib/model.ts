// Token Radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) plus every
// other rankable pre-token protocol in the snapshot: 289 rows in this snapshot, the whole pre-token
// universe the radar exists to find. A protocol is pre-token when its record carries no token (no
// market cap, no CoinGecko id, no symbol); the snapshot's live-token protocols are kept apart and
// shown as the market's own values, never mixed into the ranked board.
//
// Implied value is a comparables model, computed from the snapshot itself — no hardcoded list of
// names, no fixed multiple:
//
//   multiple   = the median FDV/TVL (mcap_usd / tvl_usd) of the live-token protocols in the same
//                category, when at least 5 of them trade; otherwise the median across all live
//                protocols (0.1691 in this snapshot). Clamped to [0.02, 2.0].
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// Why this multiple: a token's launch value is what the market already pays for the same kind of
// business. Lending protocols trade near 0.13x TVL, DEXes near 0.34x, liquid-staking near 0.03x —
// one fixed multiple for all of them would rank a staking wrapper above a DEX of the same size,
// which the market does not. The multiple is shown on every row, with its source, so the board can
// be checked line by line. No protocol name is ever special-cased: the same function scores
// every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

